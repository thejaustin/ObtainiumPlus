#!/usr/bin/env python3
"""List who translated what in Crowdin, and flag machine-made strings.

Reads every target language's translations through the Crowdin API and writes a
markdown report (default docs/CROWDIN_CONTRIBUTORS.md). Per translation Crowdin
returns `user`, `provider` (null when typed by a person; a machine engine such as
google/deepl/ai otherwise) and `isPreTranslated` (Auto-Translation). Those that
carry a provider or isPreTranslated are counted as machine, never as a person.

Translations the repo owner uploaded to seed the project (the upload workflow
ran 2026-11-27 05:22-05:32 UTC; created before --seed-cutoff) are skipped: they are older repo translations, credited by
translation-provenance.py from git history instead.

Env: CROWDIN_PROJECT_ID, CROWDIN_PERSONAL_TOKEN (needs project.translation read).
Usage: crowdin-contributors.py [--out FILE] [--seed-cutoff 2026-11-27T05:40:00Z] [--owner USERNAME]
"""
import argparse, collections, json, os, sys, urllib.request

API = "https://api.crowdin.com/api/v2"


def get(path, **q):
    url = f"{API}{path}?" + "&".join(f"{k}={v}" for k, v in q.items())
    req = urllib.request.Request(url, headers={"Authorization": "Bearer " + os.environ["CROWDIN_PERSONAL_TOKEN"]})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def pages(path, **q):
    offset = 0
    while True:
        data = get(path, limit=500, offset=offset, **q)["data"]
        if not data:
            return
        yield from (d["data"] for d in data)
        offset += len(data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/CROWDIN_CONTRIBUTORS.md")
    ap.add_argument("--seed-cutoff", default="2026-11-27T05:40:00Z")
    ap.add_argument("--owner", default="thejaustin")
    args = ap.parse_args()
    pid = os.environ["CROWDIN_PROJECT_ID"]
    langs = get(f"/projects/{pid}")["data"]["targetLanguageIds"]
    people = collections.defaultdict(collections.Counter)  # username -> lang -> n
    machine = collections.Counter()
    skipped = 0
    for lang in langs:
        for t in pages(f"/projects/{pid}/languages/{lang}/translations"):
            if t.get("provider") or t.get("isPreTranslated"):
                machine[lang] += 1
                continue
            user = t.get("user") or {}
            name = user.get("username")
            if not name or (name == args.owner and t["createdAt"] < args.seed_cutoff):
                skipped += 1
                continue
            people[name][lang] += 1
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# Crowdin contributors\n\nGenerated by `scripts/dev/crowdin-contributors.py`; do not edit by hand.\n\n")
        f.write("People who typed translations in [Crowdin](https://crowdin.com/project/obtainiumplus). ")
        f.write("Older translations carried over from the repo are credited in `TRANSLATION_CREDITS.md`.\n\n")
        f.write("| Contributor | Strings | Languages |\n|---|---|---|\n")
        for name, c in sorted(people.items(), key=lambda kv: -sum(kv[1].values())):
            f.write(f"| [{name}](https://crowdin.com/profile/{name}) | {sum(c.values())} | {', '.join(sorted(c))} |\n")
        f.write(f"\nMachine-made (Auto-Translation or MT engine), **not** credited to anyone: {sum(machine.values())}")
        if machine:
            f.write(" (" + ", ".join(f"{l} {n}" for l, n in sorted(machine.items())) + ")")
        f.write(f"\n\nSkipped as seed import: {skipped}\n")
    print(f"people={len(people)} machine={sum(machine.values())} seed_skipped={skipped}")
    if machine:
        print("::warning::Crowdin has machine-made translations; the sync merges them like any other text. Review before merging.")


if __name__ == "__main__":
    sys.exit(main())
